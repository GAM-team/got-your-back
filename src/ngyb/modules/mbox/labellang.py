IGNORED_TAKEOUT_LABELS: frozenset[str] = frozenset(
    {
        "OPENED",
        "ARCHIVED",
    }
)


def normalize_takeout_label(raw_label: str) -> tuple[str | None, bool]:
    """Normalize a single X-Gmail-Labels or Google Vault label.

    Returns ``(normalized_label_or_none, is_deleted_vault_flag)``.
    """
    cleaned = raw_label.strip()
    if not cleaned:
        return None, False
    if cleaned.startswith("^"):
        cleaned = cleaned[1:].strip()
    upper = cleaned.upper()
    if upper == "DELETED":
        return None, True
    if upper in IGNORED_TAKEOUT_LABELS:
        return None, False
    mapped = TAKEOUT_LABEL_MAPPINGS.get(upper)
    if mapped is not None:
        return mapped, False
    return cleaned, False
